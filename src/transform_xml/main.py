    if args and args[0] in (
        "--integrate-xml",
        "--merge-xml",
        "integrate-xml",
        "merge-xml",
    ):
        from transform_xml.xml_integrator import main as xml_integrate_main

        return xml_integrate_main(args[1:])

    # #4 画像XML部分変換PGの実行 (--convert-images-to-xml / --images-to-xml / convert-images-to-xml / images-to-xml)
    if args and args[0] in (
        "--convert-images-to-xml",
        "--images-to-xml",
        "convert-images-to-xml",
        "images-to-xml",
    ):
        from transform_xml.image_xml_converter import main as image_xml_main

        return image_xml_main(args[1:])

    # #3 pdf画像変換PGの実行 (--convert-pdfs / --pdf-to-images / convert-pdfs)
    if args and args[0] in ("--convert-pdfs", "--pdf-to-images", "convert-pdfs"):
        from transform_xml.pdf_image_converter import main as convert_main

        return convert_main(args[1:])

    # #2 pdf取得PGの実行 (--fetch-pdfs / --download-pdfs / fetch-pdfs)
    if args and args[0] in ("--fetch-pdfs", "--download-pdfs", "fetch-pdfs"):
        from transform_xml.pdf_downloader import main as pdf_main

        return pdf_main(args[1:])

    # #1 サイト巡回PGの実行 (--crawl / crawl)
    if args and args[0] in ("--crawl", "crawl"):
        from transform_xml.site_crawler import main as crawl_main

        return crawl_main(args[1:])

    # デフォルト動作
    message = hello_world()
    print(message)
    return None

